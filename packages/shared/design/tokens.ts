/**
 * Design token pipeline (DESIGN.md §12): tokens.json → CSS custom properties + Tailwind v4 `@theme`,
 * a small TS module for runtime values, and Android resources.
 *
 *   node packages/shared/design/tokens.ts           # write all outputs
 *   node packages/shared/design/tokens.ts --check   # fail if outputs are stale (CI)
 *
 * Runs with Node's built-in type stripping – keep this file free of enums/namespaces and relative imports.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

type Json = { [k: string]: unknown };
export type Mode = 'light' | 'dark';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '../../..');

export function loadTokens(): Json {
  return JSON.parse(readFileSync(join(HERE, 'tokens.json'), 'utf8')) as Json;
}

function lookup(tokens: Json, path: string): unknown {
  let node: unknown = tokens;
  for (const part of path.split('.')) {
    if (typeof node !== 'object' || node === null || !(part in node))
      throw new Error(`Unknown token {${path}}`);
    node = (node as Json)[part];
  }
  return node;
}

/** Resolves `{a.b}` references recursively. */
export function resolveValue(tokens: Json, value: unknown, seen: string[] = []): unknown {
  if (typeof value === 'string') {
    const m = /^\{([^}]+)\}$/.exec(value);
    if (!m) return value;
    const path = m[1]!;
    if (seen.includes(path)) throw new Error(`Circular token reference: ${[...seen, path].join(' → ')}`);
    const target = lookup(tokens, path) as Json;
    return resolveValue(tokens, target.$value, [...seen, path]);
  }
  return value;
}

/** Leaf tokens of a group as `name → resolved value` (skips `$`-keys). */
export function group(tokens: Json, path: string): Record<string, unknown> {
  const node = lookup(tokens, path) as Json;
  const out: Record<string, unknown> = {};
  for (const [k, v] of Object.entries(node)) {
    if (k.startsWith('$') || typeof v !== 'object' || v === null || !('$value' in v)) continue;
    out[k] = resolveValue(tokens, (v as Json).$value);
  }
  return out;
}

export function themeColors(tokens: Json, mode: Mode): Record<string, string> {
  return group(tokens, `theme.${mode}`) as Record<string, string>;
}

// ---------- color math (WCAG 2.x) ----------

export function hexToRgba(hex: string): [number, number, number, number] {
  const h = hex.replace('#', '');
  const full = h.length === 3 || h.length === 4 ? [...h].map((c) => c + c).join('') : h;
  const n = (i: number) => parseInt(full.slice(i, i + 2), 16);
  return [n(0), n(2), n(4), full.length === 8 ? n(6) / 255 : 1];
}

function channel(c: number) {
  const s = c / 255;
  return s <= 0.04045 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
}

export function luminance(hex: string): number {
  const [r, g, b] = hexToRgba(hex);
  return 0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b);
}

export function contrast(a: string, b: string): number {
  const [l1, l2] = [luminance(a), luminance(b)].sort((x, y) => y - x) as [number, number];
  return (l1 + 0.05) / (l2 + 0.05);
}

// ---------- generators ----------

const HEADER = 'Generated by `pnpm tokens` from packages/shared/design/tokens.json – do not edit.';

function cssValue(type: string, value: unknown): string {
  if (type === 'fontFamily' && Array.isArray(value))
    return value.map((f) => (/\s/.test(String(f)) ? `'${f}'` : f)).join(', ');
  if (type === 'cubicBezier' && Array.isArray(value)) return `cubic-bezier(${value.join(', ')})`;
  if (type === 'shadow' && typeof value === 'object' && value !== null) {
    const s = value as Record<string, string>;
    const [r, g, b, a] = hexToRgba(s.color!);
    return `${s.offsetX} ${s.offsetY} ${s.blur} ${s.spread} rgb(${r} ${g} ${b} / ${+a.toFixed(2)})`;
  }
  if (type === 'color' && typeof value === 'string') return value.toLowerCase();
  return String(value);
}

function typed(tokens: Json, path: string) {
  const node = lookup(tokens, path) as Json;
  return { type: String(node.$type ?? ''), values: group(tokens, path) };
}

/** `text-text-muted` would be awkward – these semantic colors get shorter utility names. */
const TAILWIND_COLOR_NAMES: Record<string, string> = { text: 'fg', 'text-muted': 'muted' };

export function buildCss(tokens: Json): string {
  const lines: string[] = [`/* SPDX-License-Identifier: AGPL-3.0-or-later */`, `/* ${HEADER} */`, ''];
  const block = (mode: Mode) =>
    Object.entries(themeColors(tokens, mode)).map(([k, v]) => `  --hl-${k}: ${cssValue('color', v)};`);

  const statics: string[] = [];
  const add = (prefix: string, path: string) => {
    const { type, values } = typed(tokens, path);
    for (const [k, v] of Object.entries(values)) statics.push(`  --hl-${prefix}-${k}: ${cssValue(type, v)};`);
  };
  add('font', 'font.family');
  add('text', 'font.size');
  add('leading', 'font.leading');
  add('tracking', 'font.tracking');
  add('space', 'space');
  add('size', 'size');
  add('radius', 'radius');
  add('shadow', 'shadow');
  add('duration', 'motion.duration');
  add('ease', 'motion.easing');
  add('icon', 'icon');
  add('series', 'series');

  lines.push(':root {', '  color-scheme: light;', ...block('light'), ...statics, '}', '');
  lines.push(':root[data-theme="dark"] {', '  color-scheme: dark;', ...block('dark'), '}', '');
  lines.push(
    '@media (prefers-color-scheme: dark) {',
    '  :root:not([data-theme="light"]) {',
    '    color-scheme: dark;',
    ...block('dark').map((l) => `  ${l}`),
    '  }',
    '}',
    '',
  );

  // Tailwind v4: utilities like bg-surface, text-muted, rounded-md, font-display, text-2xl, duration-fast
  const theme: string[] = ['  --color-*: initial;'];
  for (const k of Object.keys(themeColors(tokens, 'light')))
    theme.push(`  --color-${TAILWIND_COLOR_NAMES[k] ?? k}: var(--hl-${k});`);
  theme.push('  --font-*: initial;');
  for (const k of Object.keys(group(tokens, 'font.family')))
    theme.push(`  --font-${k}: var(--hl-font-${k});`);
  theme.push('  --text-*: initial;');
  const sizes = group(tokens, 'font.size');
  for (const k of Object.keys(sizes)) theme.push(`  --text-${k}: var(--hl-text-${k});`);
  theme.push(`  --spacing: var(--hl-space-base);`);
  theme.push('  --radius-*: initial;');
  for (const k of Object.keys(group(tokens, 'radius'))) theme.push(`  --radius-${k}: var(--hl-radius-${k});`);
  theme.push('  --shadow-*: initial;');
  theme.push(`  --shadow-float: var(--hl-shadow-float);`);
  for (const k of Object.keys(group(tokens, 'motion.easing')))
    theme.push(`  --ease-${k}: var(--hl-ease-${k});`);
  theme.push(`  --tracking-label: var(--hl-tracking-label);`);
  theme.push(`  --leading-display: var(--hl-leading-display);`);
  theme.push(`  --text-display--line-height: var(--hl-leading-display);`);
  theme.push(`  --container-content: var(--hl-size-content);`);
  theme.push(`  --container-form: var(--hl-size-form);`);
  for (const k of ['touch', 'content', 'form', 'rail', 'sidebar', 'fab'])
    theme.push(`  --spacing-${k}: var(--hl-size-${k});`);
  lines.push('@theme inline {', ...theme, '}', '');
  return lines.join('\n');
}

export function buildTs(tokens: Json): string {
  const series = group(tokens, 'series') as Record<string, string>;
  const light = themeColors(tokens, 'light');
  const dark = themeColors(tokens, 'dark');
  return [
    '// SPDX-License-Identifier: AGPL-3.0-or-later',
    `// ${HEADER}`,
    '',
    '/** Colors a user can pick for a series (stored as hex in the database). */',
    `export const SERIES_COLORS = ${JSON.stringify(Object.values(series).map((c) => c.toLowerCase()))} as const;`,
    '',
    '/** `<meta name="theme-color">` per mode (= `bg`). */',
    `export const THEME_COLORS = ${JSON.stringify({ light: light.bg!.toLowerCase(), dark: dark.bg!.toLowerCase() })} as const;`,
    '',
  ].join('\n');
}

function androidColor(hex: string) {
  const [r, g, b, a] = hexToRgba(hex);
  const h = (n: number) => n.toString(16).padStart(2, '0').toUpperCase();
  return a === 1 ? `#${h(r)}${h(g)}${h(b)}` : `#${h(Math.round(a * 255))}${h(r)}${h(g)}${h(b)}`;
}

const xmlName = (k: string) => k.replace(/-/g, '_');

export function buildAndroidColors(tokens: Json, mode: Mode): string {
  const out = [
    '<?xml version="1.0" encoding="utf-8"?>',
    '<!-- SPDX-License-Identifier: AGPL-3.0-or-later -->',
    `<!-- ${HEADER} -->`,
    '<resources>',
  ];
  if (mode === 'light') {
    for (const [k, v] of Object.entries(group(tokens, 'color')))
      out.push(`    <color name="hl_${xmlName(k)}">${androidColor(String(v))}</color>`);
  }
  const t = themeColors(tokens, mode);
  for (const [k, v] of Object.entries(t))
    out.push(`    <color name="hl_${xmlName(k)}">${androidColor(v)}</color>`);
  if (mode === 'light') {
    const base = group(tokens, 'color') as Record<string, string>;
    out.push(`    <color name="ic_launcher_background">${androidColor(base['navy-700']!)}</color>`);
    out.push(`    <color name="ic_launcher_foreground_ball">${androidColor(base['ball-400']!)}</color>`);
    out.push(`    <color name="splash_background">${androidColor(base['navy-950']!)}</color>`);
  }
  out.push('</resources>', '');
  return out.join('\n');
}

const px = (v: unknown) => {
  const s = String(v);
  if (s.endsWith('rem')) return parseFloat(s) * 16;
  if (s.endsWith('px')) return parseFloat(s);
  return null;
};

export function buildAndroidDimens(tokens: Json): string {
  const out = [
    '<?xml version="1.0" encoding="utf-8"?>',
    '<!-- SPDX-License-Identifier: AGPL-3.0-or-later -->',
    `<!-- ${HEADER} -->`,
    '<resources>',
  ];
  for (const [k, v] of Object.entries(group(tokens, 'space'))) {
    if (k === 'base') continue;
    out.push(`    <dimen name="hl_space_${k}">${px(v)}dp</dimen>`);
  }
  for (const [k, v] of Object.entries(group(tokens, 'size'))) {
    const n = px(v);
    if (n !== null) out.push(`    <dimen name="hl_size_${xmlName(k)}">${n}dp</dimen>`);
  }
  for (const [k, v] of Object.entries(group(tokens, 'radius'))) {
    const n = px(v);
    if (n !== null && n < 1000) out.push(`    <dimen name="hl_radius_${k}">${n}dp</dimen>`);
  }
  for (const [k, v] of Object.entries(group(tokens, 'font.size'))) {
    const n = px(v);
    if (n !== null) out.push(`    <dimen name="hl_text_${k}">${n}sp</dimen>`);
  }
  // `display` is fluid on the web; the alarm uses its upper bound
  out.push('    <dimen name="hl_text_display">64sp</dimen>');
  out.push('</resources>', '');
  return out.join('\n');
}

export function outputs(tokens: Json): Record<string, string> {
  const res = 'apps/android/android/app/src/main/res';
  return {
    'apps/web/src/lib/styles/tokens.css': buildCss(tokens),
    'apps/web/src/lib/styles/tokens.gen.ts': buildTs(tokens),
    [`${res}/values/colors.xml`]: buildAndroidColors(tokens, 'light'),
    [`${res}/values-night/colors.xml`]: buildAndroidColors(tokens, 'dark'),
    [`${res}/values/dimens.xml`]: buildAndroidDimens(tokens),
  };
}

function main() {
  const check = process.argv.includes('--check');
  const stale: string[] = [];
  for (const [file, content] of Object.entries(outputs(loadTokens()))) {
    const path = join(ROOT, file);
    let current = '';
    try {
      current = readFileSync(path, 'utf8');
    } catch {
      /* missing */
    }
    if (current === content) continue;
    if (check) stale.push(file);
    else {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, content);
      console.log(`wrote ${relative(ROOT, path)}`);
    }
  }
  if (stale.length) {
    console.error(`Design tokens are stale – run \`pnpm tokens\`:\n  ${stale.join('\n  ')}`);
    process.exit(1);
  }
  if (check) console.log('Design tokens are up to date.');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
