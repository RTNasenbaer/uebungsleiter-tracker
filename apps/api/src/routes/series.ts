import {
  addDays,
  occurrenceKey,
  planSeriesUpdate,
  seriesInput,
  seriesUpdate,
  splitSeries,
  todayIn,
} from '@ult/shared';
import { and, eq, gte, inArray } from 'drizzle-orm';
import { Hono } from 'hono';
import { HTTPException } from 'hono/http-exception';
import type { Db } from '../db';
import { series, sessions } from '../db/schema';
import type { AppEnv } from '../env';
import { newId } from '../lib/crypto';
import { seriesDto } from '../lib/dto';
import { loadExceptionDefs, materialize, toSeriesDef } from '../lib/materialize';
import { requireAuth } from '../lib/middleware';
import { parseJson } from '../lib/validate';

async function findSeries(db: Db, userId: string, id: string) {
  const row = await db.query.series.findFirst({ where: and(eq(series.id, id), eq(series.userId, userId)) });
  if (!row) throw new HTTPException(404, { message: 'Training nicht gefunden' });
  return row;
}

/** Applies a changed series definition to its already materialized future sessions. */
async function syncFutureSessions(db: Db, userId: string, row: typeof series.$inferSelect, today: string) {
  const existing = await db
    .select({
      occurrenceKey: sessions.occurrenceKey,
      date: sessions.date,
      status: sessions.status,
      isOverride: sessions.isOverride,
    })
    .from(sessions)
    .where(and(eq(sessions.userId, userId), eq(sessions.seriesId, row.id), gte(sessions.date, today)));
  const exDefs = await loadExceptionDefs(db, userId, { from: today, to: addDays(today, 400) });
  const plan = planSeriesUpdate(toSeriesDef(row), existing, today, exDefs);
  const ops = [];
  if (plan.deleteKeys.length) {
    ops.push(
      db
        .delete(sessions)
        .where(and(eq(sessions.userId, userId), inArray(sessions.occurrenceKey, plan.deleteKeys))),
    );
  }
  if (plan.updateKeys.length) {
    ops.push(
      db
        .update(sessions)
        .set({
          title: row.title,
          team: row.team,
          location: row.location,
          startTime: row.startTime,
          endTime: row.endTime,
          units: row.units,
          payCents: row.payCents,
          alarmOffsetMin: row.alarmOffsetMin,
        })
        .where(and(eq(sessions.userId, userId), inArray(sessions.occurrenceKey, plan.updateKeys))),
    );
  }
  const [first, ...rest] = ops;
  if (first) await db.batch([first, ...rest]);
}

export const seriesRoutes = new Hono<AppEnv>()
  .use(requireAuth)
  .get('/', async (c) => {
    const rows = await c
      .get('db')
      .select()
      .from(series)
      .where(eq(series.userId, c.get('userId')))
      .orderBy(series.startsOn);
    return c.json(rows.map(seriesDto));
  })
  .post('/', async (c) => {
    const db = c.get('db');
    const userId = c.get('userId');
    const now = c.get('clock').now();
    const input = await parseJson(c, seriesInput);
    const [row] = await db
      .insert(series)
      .values({ ...input, id: newId(), userId })
      .returning();
    // past occurrences become "pending" immediately → Nachtragen
    const today = todayIn(c.get('clock'));
    const created = await materialize(db, userId, { from: row!.startsOn, to: addDays(today, 28) }, now, [
      row!,
    ]);
    return c.json({ series: seriesDto(row!), createdSessions: created }, 201);
  })
  .put('/:id', async (c) => {
    const db = c.get('db');
    const userId = c.get('userId');
    const now = c.get('clock').now();
    const today = todayIn(c.get('clock'));
    const existing = await findSeries(db, userId, c.req.param('id'));
    const { series: input, scope, fromDate } = await parseJson(c, seriesUpdate);

    if (scope === 'following') {
      if (!fromDate) throw new HTTPException(400, { message: 'fromDate fehlt' });
      if (fromDate <= existing.startsOn) {
        // splitting at (or before) the first date is the same as editing everything
        return c.json(await updateAll());
      }
      const { ended } = splitSeries(toSeriesDef(existing), fromDate, newId());
      const newSeriesId = newId();
      const [next] = await db.batch([
        db
          .insert(series)
          .values({
            ...input,
            id: newSeriesId,
            userId,
            startsOn: fromDate,
            endsOn: input.endsOn ?? existing.endsOn,
          })
          .returning(),
        db
          .update(series)
          .set({ endsOn: ended.endsOn, updatedAt: now.toISOString() })
          .where(and(eq(series.id, existing.id), eq(series.userId, userId))),
      ]);
      const nextRow = next[0]!;
      // Unanswered, non-overridden sessions after the split are regenerated by the new series.
      await db
        .delete(sessions)
        .where(
          and(
            eq(sessions.userId, userId),
            eq(sessions.seriesId, existing.id),
            gte(sessions.date, fromDate),
            inArray(sessions.status, ['planned', 'pending']),
            eq(sessions.isOverride, false),
          ),
        );
      // Remaining ones (answered/overridden) move to the new series so no duplicates appear.
      const moved = await db
        .select({ id: sessions.id, date: sessions.date })
        .from(sessions)
        .where(
          and(eq(sessions.userId, userId), eq(sessions.seriesId, existing.id), gte(sessions.date, fromDate)),
        );
      const [m0, ...mRest] = moved.map((m) =>
        db
          .update(sessions)
          .set({ seriesId: nextRow.id, occurrenceKey: occurrenceKey(nextRow.id, m.date) })
          .where(and(eq(sessions.id, m.id), eq(sessions.userId, userId))),
      );
      if (m0) await db.batch([m0, ...mRest]);
      await materialize(db, userId, { from: fromDate, to: addDays(today, 28) }, now, [nextRow]);
      return c.json({
        series: seriesDto(nextRow),
        previous: seriesDto({ ...existing, endsOn: ended.endsOn }),
      });
    }
    return c.json(await updateAll());

    async function updateAll() {
      const [row] = await db
        .update(series)
        .set({ ...input, updatedAt: now.toISOString() })
        .where(and(eq(series.id, existing.id), eq(series.userId, userId)))
        .returning();
      await syncFutureSessions(db, userId, row!, today);
      await materialize(
        db,
        userId,
        { from: row!.startsOn < today ? row!.startsOn : today, to: addDays(today, 28) },
        now,
        [row!],
      );
      return { series: seriesDto(row!) };
    }
  })
  .delete('/:id', async (c) => {
    const db = c.get('db');
    const userId = c.get('userId');
    const today = todayIn(c.get('clock'));
    const existing = await findSeries(db, userId, c.req.param('id'));
    // answered sessions stay (they are the proof); only future unanswered ones are removed
    await db.batch([
      db
        .delete(sessions)
        .where(
          and(
            eq(sessions.userId, userId),
            eq(sessions.seriesId, existing.id),
            gte(sessions.date, today),
            eq(sessions.status, 'planned'),
          ),
        ),
      db.delete(series).where(and(eq(series.id, existing.id), eq(series.userId, userId))),
    ]);
    return c.json({ ok: true });
  });
